def translate_obd_title(value: Any, language: str) -> str:
    text = str(value or "").strip()
    replacements = _OBD_PHRASES.get(language)
    if not text or not replacements:
        return text

    ordered = sorted(replacements, key=lambda item: len(item[0]), reverse=True)
    localized_by_source = {source.casefold(): localized for source, localized in ordered}
    pattern = re.compile(
        r"(?<![A-Za-z])(?:"
        + "|".join(re.escape(source) for source, _localized in ordered)
        + r")(?![A-Za-z])",
        flags=re.IGNORECASE,
    )
    output = pattern.sub(
        lambda match: localized_by_source[match.group(0).casefold()],
        text,
    )

    output = re.sub(r"\s+", " ", output).strip()
    if language == "zh-Hans":
        output = re.sub(r"(?<=[\u3400-\u9fff])\s+(?=[\u3400-\u9fff])", "", output)
    return output
