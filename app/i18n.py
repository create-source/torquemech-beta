def normalize_language(value: Any) -> str:
    clean = str(value or "").strip()
    return clean if clean in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, language: Any = DEFAULT_LANGUAGE) -> str:
    lang = normalize_language(language)
    return TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key


def request_language(request: Any) -> str:
    user = getattr(getattr(request, "state", None), "current_user", None)
    try:
        return normalize_language(user.get("language_preference"))
    except AttributeError:
        return normalize_language(getattr(user, "language_preference", ""))


def t_for_request(request: Any, key: str) -> str:
    return t(key, request_language(request))


def client_payload(language: Any) -> dict[str, Any]:
    lang = normalize_language(language)
    return {
        "language": lang,
        "translations": TRANSLATIONS.get(lang, {}),
        "exactText": EXACT_TEXT_TRANSLATIONS_ES if lang == "es" else {},
    }


def client_payload_json(language: Any) -> str:
    return json.dumps(client_payload(language), ensure_ascii=False)
