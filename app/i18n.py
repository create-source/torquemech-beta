def _localized_ui_text(text: str, language: str) -> str:
    if not text:
        return text
    glossary = _PHRASE_TRANSLATIONS.get(language, {})
    output = text
    placeholders: dict[str, str] = {}
    for index, value in enumerate(re.findall(r"\{[^}]+\}|<[^>]+>|&[a-zA-Z0-9#]+;", output)):
        token = f"__TM_TOKEN_{index}__"
        placeholders[token] = value
        output = output.replace(value, token)
    changed = False
    for source, translated in sorted(glossary.items(), key=lambda item: len(item[0]), reverse=True):
        next_output = output.replace(source, translated)
        changed = changed or next_output != output
        output = next_output
    if not changed:
        output = _LOCALIZED_UI_FALLBACKS.get(language, text)
    for token, value in placeholders.items():
        output = output.replace(token, value)
    return output


def _localized_ui_map(source: dict[str, str], language: str) -> dict[str, str]:
    return {key: _localized_ui_text(value, language) for key, value in source.items()}


