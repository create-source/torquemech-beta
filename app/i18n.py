def normalize_language(value: Any) -> str:
    clean = str(value or "").strip()
    aliases = {
        "": DEFAULT_LANGUAGE,
        "en-us": "en",
        "en_us": "en",
        "en": "en",
        "es-es": "es",
        "es_us": "es",
        "vi-vn": "vi",
        "zh": "zh-Hans",
        "zh-cn": "zh-Hans",
        "zh_hans": "zh-Hans",
        "zh-hans": "zh-Hans",
    }
    normalized = aliases.get(clean.lower(), clean)
    return normalized if normalized in LOCALE_REGISTRY else DEFAULT_LANGUAGE


def locale_meta(language: Any = DEFAULT_LANGUAGE) -> dict[str, str]:
    return dict(LOCALE_REGISTRY[normalize_language(language)])


def locale_options() -> list[dict[str, str]]:
    return [dict(meta) for meta in LOCALE_REGISTRY.values()]


def catalog_report() -> dict[str, dict[str, list[str]]]:
    english_keys = set(TRANSLATIONS["en"])
    report: dict[str, dict[str, list[str]]] = {}
    for locale in SUPPORTED_LANGUAGES:
        keys = set(TRANSLATIONS.get(locale, {}))
        report[locale] = {
            "missing": sorted(english_keys - keys),
            "unknown": sorted(keys - english_keys),
        }
    return report


def t(key: str, language: Any = DEFAULT_LANGUAGE) -> str:
    lang = normalize_language(language)
    return TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS["en"].get(key) or key


def request_language(request: Any) -> str:
    user = getattr(getattr(request, "state", None), "current_user", None)
    try:
        return normalize_language(user.get("language_preference"))
    except AttributeError:
        return normalize_language(getattr(user, "language_preference", ""))


def t_for_request(request: Any, key: str) -> str:
    return t(key, request_language(request))


def translate_text(value: Any, language: Any = DEFAULT_LANGUAGE) -> str:
    text = str(value or "")
    lang = normalize_language(language)
    exact = EXACT_TEXT_TRANSLATIONS.get(lang, {})
    if not exact:
        return text
    clean = " ".join(text.split())
    translated = exact.get(clean)
    if not translated:
        return text
    prefix = text[: len(text) - len(text.lstrip())]
    suffix = text[len(text.rstrip()) :]
    return f"{prefix}{translated}{suffix}"


def translate_text_for_request(request: Any, value: Any) -> str:
    return translate_text(value, request_language(request))


def client_payload(language: Any) -> dict[str, Any]:
    lang = normalize_language(language)
    if lang == "en":
        return {
            "language": "en",
            "locale": locale_meta("en"),
            "locales": locale_options(),
            "translations": {},
            "fallbackTranslations": {},
            "exactText": {},
        }
    return {
        "language": lang,
        "locale": locale_meta(lang),
        "locales": locale_options(),
        "translations": TRANSLATIONS.get(lang, {}),
        "fallbackTranslations": TRANSLATIONS["en"],
        "exactText": EXACT_TEXT_TRANSLATIONS.get(lang, {}),
    }


def client_payload_json(language: Any) -> str:
    return json.dumps(client_payload(language), ensure_ascii=False)


def public_client_payload(language: Any) -> dict[str, Any]:
    lang = normalize_language(language)
    allowed_keys = {
        "footer.terms",
        "footer.privacy",
        "footer.disclaimer",
        "footer.support",
        "footer.feedback",
    }
    return {
        "language": lang,
        "locale": locale_meta(lang),
        "locales": locale_options(),
        "translations": {key: t(key, lang) for key in sorted(allowed_keys)},
        "fallbackTranslations": {key: t(key, "en") for key in sorted(allowed_keys)},
        "exactText": PUBLIC_EXACT_TEXT_TRANSLATIONS.get(lang, {}),
    }


def public_client_payload_json(language: Any) -> str:
    return json.dumps(public_client_payload(language), ensure_ascii=False)
